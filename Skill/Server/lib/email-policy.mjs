import { createHash } from "node:crypto";

const SUPPORTED_OPERATIONS = new Set([
  "inspect",
  "connect_domain",
  "create_account",
  "reset_password",
  "disable_account",
  "send_mail",
  "read_mail",
  "permission_change",
  "runtime_change",
]);

const GRANTS_BY_OPERATION = {
  inspect: ["email.inspect"],
  connect_domain: ["email.domain.write"],
  create_account: ["email.account.write"],
  reset_password: ["email.account.write"],
  disable_account: ["email.account.write"],
  send_mail: ["email.mail.send"],
  read_mail: ["email.mail.read"],
  permission_change: ["email.permission.write"],
  runtime_change: ["email.runtime.admin"],
};

const SECRET_FIELD_NAMES = new Set([
  "apiKey",
  "password",
  "passwordHash",
  "privateKey",
  "token",
]);

export function classifyEmailOperation(input) {
  const operationType = normalizeOperationType(input.operationType);
  const environment = normalizeEnvironment(input.environment);

  return {
    operationType,
    runtimeMode: "kubernetes-mail-runtime",
    riskLevel: resolveRiskLevel(operationType, environment, input),
    approvalRequired: requiresApproval(operationType, environment, input),
    evidenceRequired: requiresEvidence(operationType),
    auditRequired: true,
    requiredGrants: GRANTS_BY_OPERATION[operationType],
    requiredDnsRecords:
      operationType === "connect_domain" ? buildDomainDnsChecklist(input) : [],
    reason: explainDecision(operationType, environment, input),
  };
}

export function createEmailOperationRecord(input) {
  assertNoSecretFields(input);

  requireNonEmpty(input.domainId, "domainId");
  requireNonEmpty(input.environmentId, "environmentId");
  requireNonEmpty(input.actor?.type, "actor.type");
  requireNonEmpty(input.actor?.id, "actor.id");

  const requestedAt = input.requestedAt ?? new Date().toISOString();
  const classification = classifyEmailOperation({
    ...input,
    environment: input.environment ?? input.environmentId,
  });
  const target = clonePlainObject(input.target ?? {});
  const targetFingerprint = sha256(JSON.stringify(target));
  const operationId = `emailop_${sha256(
    [
      input.domainId,
      input.environmentId,
      classification.operationType,
      input.actor.type,
      input.actor.id,
      requestedAt,
      targetFingerprint,
    ].join("\u001f"),
  ).slice(0, 16)}`;

  return {
    operationId,
    domainId: input.domainId,
    environmentId: input.environmentId,
    operationType: classification.operationType,
    actor: {
      type: input.actor.type,
      id: input.actor.id,
    },
    target,
    requestedAt,
    classification,
    proxy: {
      mode: "doemail-agent-proxy",
      status: "planned",
    },
    audit: {
      captured: true,
      immutableFields: [
        "operationId",
        "domainId",
        "environmentId",
        "operationType",
        "actor",
        "target",
        "requestedAt",
      ],
    },
  };
}

function buildDomainDnsChecklist(input) {
  requireNonEmpty(input.domain, "domain");
  requireNonEmpty(input.mailHostname, "mailHostname");

  const publicIp = input.publicIp ?? "<mail-server-public-ip>";
  const dkimSelector = input.dkimSelector ?? "default";
  const dkimValue = input.dkimPublicKey ?? "<dkim-public-key>";

  return [
    {
      type: "A",
      name: `${input.mailHostname}.`,
      expected: `${input.mailHostname}. A ${publicIp}`,
      purpose: "Point the mail hostname to the Kubernetes mail node public IP.",
    },
    {
      type: "MX",
      name: `${input.domain}.`,
      expected: `${input.domain}. MX 10 ${input.mailHostname}.`,
      purpose: "Route inbound mail for the domain to the DoEmail runtime.",
    },
    {
      type: "SPF",
      name: `${input.domain}.`,
      expected: `${input.domain}. TXT "v=spf1 mx -all"`,
      purpose: "Authorize the MX host to send mail for the domain.",
    },
    {
      type: "DKIM",
      name: `${dkimSelector}._domainkey.${input.domain}.`,
      expected: `${dkimSelector}._domainkey.${input.domain}. TXT "v=DKIM1; k=rsa; p=${dkimValue}"`,
      purpose: "Publish the DKIM public key generated by the mail runtime.",
    },
    {
      type: "DMARC",
      name: `_dmarc.${input.domain}.`,
      expected: `_dmarc.${input.domain}. TXT "v=DMARC1; p=none; rua=mailto:postmaster@${input.domain}"`,
      purpose: "Start domain authentication reporting before enforcing reject policy.",
    },
    {
      type: "rDNS",
      name: publicIp,
      expected: `${publicIp} reverse DNS/PTR -> ${input.mailHostname}`,
      purpose: "Ask the IP provider to set reverse DNS for outbound deliverability.",
    },
  ];
}

function resolveRiskLevel(operationType, environment, input) {
  if (operationType === "inspect") return "low";
  if (operationType === "read_mail") {
    return input.mailboxAccess === "self" ? "medium" : "high";
  }
  if (operationType === "send_mail") {
    return environment === "prod" && input.externalDelivery ? "high" : "medium";
  }
  if (["create_account", "reset_password", "disable_account"].includes(operationType)) {
    return environment === "prod" ? "high" : "medium";
  }
  return "high";
}

function requiresApproval(operationType, environment, input) {
  if (operationType === "inspect") return false;
  if (operationType === "read_mail") return input.mailboxAccess !== "self";
  if (operationType === "send_mail") {
    return environment === "prod" && Boolean(input.externalDelivery);
  }
  if (["connect_domain", "permission_change", "runtime_change"].includes(operationType)) {
    return true;
  }
  if (["create_account", "reset_password", "disable_account"].includes(operationType)) {
    return environment === "prod";
  }
  return true;
}

function requiresEvidence(operationType) {
  return operationType !== "read_mail";
}

function explainDecision(operationType, environment, input) {
  if (operationType === "connect_domain") {
    return "Mail domain connection changes DNS, reverse DNS and Kubernetes mail routing.";
  }
  if (operationType === "read_mail" && input.mailboxAccess === "self") {
    return "Self mailbox reads are audited and allowed with mailbox read permission.";
  }
  if (operationType === "runtime_change") {
    return "Kubernetes mail runtime changes affect SMTP/IMAP availability and stored mail.";
  }
  if (environment === "prod") {
    return "Production email changes require audit and policy checks.";
  }
  return "Email operation is classified for DoEmail agent execution.";
}

function normalizeOperationType(operationType) {
  const normalized = String(operationType ?? "").toLowerCase();
  if (!SUPPORTED_OPERATIONS.has(normalized)) {
    throw new Error(`Unsupported email operation: ${operationType}`);
  }
  return normalized;
}

function normalizeEnvironment(environment) {
  const normalized = String(environment ?? "dev").toLowerCase();
  return normalized === "production" ? "prod" : normalized;
}

function assertNoSecretFields(value, path = "") {
  if (value === null || value === undefined || typeof value !== "object") {
    return;
  }
  if (Array.isArray(value)) {
    value.forEach((item, index) => assertNoSecretFields(item, `${path}[${index}]`));
    return;
  }
  for (const [key, nestedValue] of Object.entries(value)) {
    const nestedPath = path ? `${path}.${key}` : key;
    if (SECRET_FIELD_NAMES.has(key)) {
      throw new Error(`${nestedPath} must not be stored in operation records`);
    }
    assertNoSecretFields(nestedValue, nestedPath);
  }
}

function clonePlainObject(value) {
  return JSON.parse(JSON.stringify(value));
}

function requireNonEmpty(value, fieldName) {
  if (value === undefined || value === null || String(value).trim() === "") {
    throw new Error(`${fieldName} is required`);
  }
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}
